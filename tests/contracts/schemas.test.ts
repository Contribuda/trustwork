test('free text is NFC-normalised at validation and e-mails are lower-cased', () => {
  assert.equal(c.NameSchema.parse('й'), 'й');
  assert.equal(c.EmailSchema.parse('Ivan@Example.Invalid'), 'ivan@example.invalid');
  assert.equal(c.passwordSchema().parse('й'.repeat(16)), 'й'.repeat(16));
  assert.equal(c.passwordSchema().safeParse('й'.repeat(8)).success, false, 'length is measured after normalization');
  assert.ok(c.ShortTextSchema.safeParse('\u0438\u0306'.repeat(500)).success, 'max applies to the NFC form (500 composed characters)');
  assert.equal(c.ShortTextSchema.safeParse('\u0439'.repeat(501)).success, false);
  assert.ok(c.NameSchema.safeParse('\u0438\u0306'.repeat(200)).success);
});
