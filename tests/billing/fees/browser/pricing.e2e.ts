import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const evidence = process.env.BILL003_EVIDENCE_DIR ?? resolve(import.meta.dirname, '../evidence');
const languages = ['en', 'es', 'ru', 'uz-Latn', 'ka', 'hy', 'az-Latn'];
test('actual public API: coverage, all seven languages and three widths, axe, keyboard and refusal', async ({ page, request }) => {
  mkdirSync(evidence, { recursive: true });
  const control = async (path: string) => expect((await request.post(`http://127.0.0.1:3542/${path}`)).status()).toBe(200);
  await page.goto('/ru/pricing');
  await expect(page.locator('h1')).toHaveText('Цены и комиссии');
  await expect(page.locator('[data-pricing-state]')).toHaveAttribute('data-pricing-state','partial');
  await expect(page.locator('[data-section="fees"]')).toHaveAttribute('data-coverage','empty');
  await expect(page.locator('[data-section="models"]')).toHaveAttribute('data-coverage','unavailable');
  await expect(page.locator('.fee-pricing-row')).toHaveCount(0);
  await page.screenshot({ path: resolve(evidence, 'pricing-ru-empty-1280.png'), fullPage: true });
  await control('publish');
  const publicResponse = await request.get('http://127.0.0.1:3541/v1/pricing');
  expect(publicResponse.status()).toBe(200);
  const snapshot = await publicResponse.json();
  writeFileSync(resolve(evidence,'synthetic-public-projection.json'),JSON.stringify(snapshot,null,2));
  const scans = [];
  for (const lang of languages) {
    for (const width of [375, 768, 1280]) {
      await page.setViewportSize({width,height:900});
      await page.goto(lang === 'en' ? '/pricing' : `/${lang}/pricing`);
      await expect(page.locator('html')).toHaveAttribute('lang',lang);
      await expect(page.locator('.fee-pricing-row')).toHaveCount(5);
      await expect(page.locator('.fee-pricing-hub')).toContainText(snapshot.hubId);
      await expect(page.locator('#pricing-fees-current')).toBeVisible();
      await expect(page.locator('#pricing-fees-future')).toBeVisible();
      await expect(page.locator('.fee-pricing-state')).toHaveCount(2);
      expect(await page.locator('.fee-pricing-amount').allTextContents()).toEqual(expect.arrayContaining([expect.stringContaining('USD')]));
      expect((await page.locator('.fee-pricing-amount').allTextContents()).some(s=>s.replace(/[^0-9]/g,'')==='9223372036854775807')).toBe(true);
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
      const summary = page.locator('.fee-pricing-reference summary').first();
      await summary.focus(); await page.keyboard.press('Enter');
      await expect(page.locator('.fee-pricing-reference').first()).toHaveAttribute('open','');
      await page.keyboard.press('Enter');
      await expect(page.locator('.fee-pricing-reference').first()).not.toHaveAttribute('open','');
      const link=page.locator('.fee-pricing-index a[href="#pricing-fees"]');
      await link.focus(); await page.keyboard.press('Enter');
      await expect(page).toHaveURL(/#pricing-fees$/);
      await expect(page.locator('#pricing-fees')).toBeFocused();
      await page.keyboard.press('Tab');
      await expect(page.locator('[data-section="fees"] summary').first()).toBeFocused();
      const scan=await new AxeBuilder({page}).include('.fee-pricing').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
      scans.push({lang,width,violations:scan.violations,passes:scan.passes.length});
      writeFileSync(resolve(evidence,'axe.json'),JSON.stringify(scans,null,2));
      expect(scan.violations).toEqual([]);
      await page.screenshot({path:resolve(evidence,`pricing-${lang}-${width}.png`),fullPage:true});
    }
  }
  await page.goto('/ru/pricing');
  await control('partial'); await page.reload();
  await expect(page.locator('[data-section="plans"]')).toHaveAttribute('data-coverage','error');
  await expect(page.locator('[data-section="services"] .fee-pricing-row')).toHaveCount(1);
  await page.screenshot({path:resolve(evidence,'pricing-ru-reader-error.png'),fullPage:true});
  await control('restore'); await control('error'); await page.reload();
  await expect(page.locator('[data-pricing-state]')).toHaveAttribute('data-pricing-state','error');
  await expect(page.locator('.fee-pricing-row')).toHaveCount(0);
  await page.screenshot({path:resolve(evidence,'pricing-ru-error.png'),fullPage:true});
  await control('restore');
  await page.locator('.fee-pricing-retry').click();
  await expect(page.locator('.fee-pricing-row')).toHaveCount(5);
  const denied=await page.evaluate(async()=> (await fetch('/v1/admin/billing/fees',{method:'POST',headers:{'content-type':'application/json','X-Trustwork-Request':'1','idempotency-key':'synthetic-browser-denied'},body:JSON.stringify({reason:'Synthetic unauthorized browser test',terms:{}})})).status);
  expect(denied).toBe(401);
  await control('closed'); await page.reload();
  await expect(page.locator('[data-pricing-state]')).toHaveAttribute('data-pricing-state','unconfigured');
  await expect(page.locator('.fee-pricing-row')).toHaveCount(0);
  await expect(page.locator('[data-section="fees"]')).toHaveAttribute('data-coverage','unavailable');
  await page.screenshot({path:resolve(evidence,'pricing-ru-unconfigured.png'),fullPage:true});
});
