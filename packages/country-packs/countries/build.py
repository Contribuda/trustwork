"""Regenerates countries.json from a downloaded copy of https://github.com/mledoze/countries (ODbL 1.0).

  python3 build.py /path/to/countries.json

Restricted places (ADR-009) are dropped; packs are flagged by the codes in PACKS.
"""
import json
import sys

RESTRICTED = {'RU', 'CU', 'IR', 'KP'}
PACKS = {'UZ', 'GE', 'AM', 'AZ', 'US', 'GB'}
src = json.load(open(sys.argv[1], encoding='utf-8'))
out = []
for c in src:
    code = c['cca2']
    if code in RESTRICTED:
        continue
    cur = sorted(c.get('currencies', {}).keys())
    idd = c.get('idd', {})
    calling = (idd.get('root', '') + (idd.get('suffixes') or [''])[0]) or None
    out.append({
        'code': code,
        'name': {'en': c['name']['common'], 'ru': c['translations'].get('rus', {}).get('common', c['name']['common'])},
        'currency': cur[0] if cur else None,
        'currencies': cur,
        'region': c.get('region'),
        'subregion': c.get('subregion'),
        'independent': bool(c.get('independent')),
        'unMember': bool(c.get('unMember')),
        'callingCode': calling,
        'timeZones': c.get('timezones', []),
        'pack': code in PACKS,
    })
out.sort(key=lambda x: x['code'])
doc = {
    '$comment': 'All ISO 3166-1 alpha-2 countries and territories except the restricted places of ADR-009, generated by packages/country-packs/countries/build.py from mledoze/countries (ODbL 1.0); see PROVENANCE.md.',
    'generatedFrom': 'https://github.com/mledoze/countries (countries.json)',
    'countries': out,
}
json.dump(doc, open('countries.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(len(out), 'countries')
