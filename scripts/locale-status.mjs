#!/usr/bin/env node
// Prints the languages table of docs/engine/localization.md from apps/web/locales/<tag>.meta.json (INTL-007).
//   node scripts/locale-status.mjs           the table
//   node scripts/locale-status.mjs --write   rewrites the table in the chapter, between its markers
//   node scripts/locale-status.mjs --check   fails when the chapter differs from the metadata
//   node scripts/locale-status.mjs --json    every language in the machine-readable form
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';
import { REFERENCE_LOCALE_TAG, readLocaleReview, reviewStatement, shownStatus } from '../packages/i18n-runtime/src/review-status.ts';

const ROOT = resolve(import.meta.dirname, '..');
const LOCALES = join(ROOT, 'apps/web/locales');
const CHAPTER = join(ROOT, 'docs/engine/localization.md');
const BEGIN = '<!-- locale-status:begin (generated by scripts/locale-status.mjs --write) -->';
const END = '<!-- locale-status:end -->';

/** Every language with a dictionary directory, the reference first. A directory without metadata still counts. */
function languageTags(root) {
  return readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => (a === REFERENCE_LOCALE_TAG ? -1 : b === REFERENCE_LOCALE_TAG ? 1 : a.localeCompare(b)));
}

function readReview(root, tag) {
  const file = join(root, `${tag}.meta.json`);
  return readLocaleReview(tag, existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : undefined);
}

function namespaces(root) {
  return readdirSync(join(root, REFERENCE_LOCALE_TAG))
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -5));
}

const languageName = (tag) => new Intl.DisplayNames(['en'], { type: 'language' }).of(tag) ?? tag;
const cell = (value) => (value ? value.replaceAll('|', '\\|') : '—');

function reviewRecord(review) {
  if (!review.reviewedOn) return '—';
  return `${review.reviewers.map((handle) => `\`${handle}\``).join(', ')}, ${review.reviewedOn}, ${review.namespaces.map((name) => `\`${name}\``).join(', ')}, [review](${review.reviewLink})`;
}

export function languagesTable(root = LOCALES) {
  const labels = JSON.parse(readFileSync(join(root, REFERENCE_LOCALE_TAG, 'translations.json'), 'utf8')).translations.status;
  const all = namespaces(root);
  const rows = languageTags(root).map((tag) => {
    const review = readReview(root, tag);
    return `| \`${tag}\` | ${languageName(tag)} | ${labels[shownStatus(review, all)].label} | ${reviewRecord(review)} | ${cell(review.package)} | ${cell(review.note)} |`;
  });
  return ['| Tag | Language | Review status | Review record | Package | Notes |', '|---|---|---|---|---|---|', ...rows].join('\n');
}

export function languagesStatement(root = LOCALES) {
  return reviewStatement(languageTags(root).map((tag) => ({ tag, review: readReview(root, tag) })), namespaces(root));
}

/** Where the table sits in the chapter: the offsets just inside its markers. */
function tableBounds(chapter) {
  const from = chapter.indexOf(BEGIN);
  const to = chapter.indexOf(END);
  if (from === -1 || to < from) throw new Error(`${CHAPTER}: the locale-status markers are missing`);
  return [from + BEGIN.length, to];
}

/** The table in the chapter, between its markers. */
export function chapterTable(chapter) {
  const [from, to] = tableBounds(chapter);
  return chapter.slice(from, to).trim();
}

function main(mode) {
  const table = languagesTable();
  if (mode === '--json') return console.log(JSON.stringify(languagesStatement(), null, 2));
  if (!mode) return console.log(table);
  const chapter = readFileSync(CHAPTER, 'utf8');
  if (mode === '--write') {
    const [from, to] = tableBounds(chapter);
    return writeFileSync(CHAPTER, `${chapter.slice(0, from)}\n${table}\n${chapter.slice(to)}`);
  }
  if (mode !== '--check') throw new Error(`unknown option ${mode}`);
  if (chapterTable(chapter) !== table) {
    console.error('docs/engine/localization.md differs from the locale metadata; run node scripts/locale-status.mjs --write');
    process.exitCode = 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv[2]);
